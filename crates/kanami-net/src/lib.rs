//! Kanami 网络层：发现、信令、音频传输。
//!
//! 设计完全由实测环境倒推出来，不是教科书式的「标准做法」：
//!
//! 1. **连接由播放端发起。** 实测宿主无法主动寻址到 QEMU NAT 后面的客体，
//!    而客体主动发出的包能到达宿主。所以握手必须从接收方发起。
//! 2. **音源端从收到的包学习对端地址。** 实测对端源端口每次随机
//!    （54255/59171/65134/63610…），硬编码端口必然失败。
//! 3. **回程 socket 长期绑定同一本地端口。** 实测对称 NAT 只接受
//!    从同一源端口回送的包，换端口就被丢弃。
//! 4. **保活 60 秒。** 实测映射 180 秒空闲仍存活，留三倍余量。
//! 5. **发现要三件套。** 实测模拟器上广播与组播双向都不通，
//!    所以 mDNS 之外必须有 UDP 广播和手动 IP 兜底。

