//! Kanami 音频内核。
//!
//! 这个 crate 不依赖 Tauri、不依赖任何 UI，可以单独测试、单独用命令行跑。
//! 里面装的是整条链路里最容易出错、也最需要回归保护的部分：
//!
//! - 抖动缓冲：把乱序/迟到/重复的包整理成连续帧流。
//! - 混音：多路音源叠加，f32 累加后软限幅，绝不整数相加爆音。
//! - 漂移校正：每路音源与本地输出时钟存在独立晶振差，靠水位反馈微调重采样比率。

#![forbid(unsafe_code)]

pub mod jitter;
pub mod mixer;
pub mod resample;

/// 内部统一使用的采样率。采集端若不在这个速率上，采集时就要重采样。
pub const SAMPLE_RATE: u32 = 48_000;
/// 声道数。v1 固定立体声，单声道音源在混音时复制到两个声道。
pub const CHANNELS: usize = 2;
